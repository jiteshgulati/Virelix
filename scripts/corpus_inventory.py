#!/usr/bin/env python3
"""Generate docs/corpus-inventory.md and corpus/inventory.json from the real loader output.

Usage:  python scripts/corpus_inventory.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.search.loader import load_corpus  # noqa: E402
from backend.search.preprocess import tokenize  # noqa: E402


def main() -> int:
    report = load_corpus(ROOT / "corpus")
    rows = []
    for d in report.documents:
        rows.append({
            "doc_id": d.doc_id, "filename": d.filename, "title": d.title,
            "category": d.metadata.get("category"), "tags": d.metadata.get("tags", []),
            "date": d.metadata.get("date"), "words": len(d.text.split()),
            "tokens": len(tokenize(f"{d.title}\n{d.text}")), "bytes": d.size_bytes, "encoding": d.encoding,
        })
    (ROOT / "corpus" / "inventory.json").write_text(json.dumps({"counts": report.counts, "documents": rows}, indent=2) + "\n", encoding="utf-8")
    cats = {}
    for r in rows:
        cats[r["category"]] = cats.get(r["category"], 0) + 1
    c = report.counts
    lines = [
        "# Sample corpus inventory",
        "",
        "Generated by `python scripts/corpus_inventory.py` from the Week 1 loader. Don't edit by hand.",
        "",
        f"- **Documents loaded:** {c['loaded']} of {c['discovered']} files ({c['total_bytes']:,} bytes); skipped: {c['skipped']}",
        f"- **Total words:** {sum(r['words'] for r in rows):,} · **tokens after preprocessing:** {sum(r['tokens'] for r in rows):,}",
        f"- **Subjects:** {len(cats)} — " + ", ".join(f"{k} ({v})" for k, v in sorted(cats.items())),
        "- **Format:** UTF-8 `.txt` with a `Key: value` metadata header (Title, Author, Category, Tags, Date, Source) ended by `---`.",
        "- **Authorship:** original explanatory texts written for this project by Virelix Editorial (G393) for testing retrieval.",
        "",
        "| # | Document ID | File | Title | Subject | Words |",
        "|---|---|---|---|---|---:|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | `{r['doc_id']}` | `{r['filename']}` | {r['title']} | {r['category']} | {r['words']} |")
    (ROOT / "docs" / "corpus-inventory.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote inventory for {len(rows)} documents.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
